# ------------------------------------------------------------ tenant isolation

def test_tenant_isolation_engine_level():
    """Engine-level: tenant filtering via metadata, multi-tenant restore,
    and forget_tenant remove only that tenant's records + index entries."""
    async def scenario():
        system = MemorySystem(max_entries=100)

        async def put(mid, tid):
            await system.store(content=f"data {mid}", memory_type=MemoryType.EPISODIC,
                               tags={"shared"}, metadata={"tenant_id": tid},
                               memory_id=mid)

        await asyncio.gather(put("a1", "t1"), put("a2", "t1"),
                             put("b1", "t2"), put("b2", "t2"),
                             put("q1", None))  # quarantined: no tenant

        # per-tenant search never crosses tenants, quarantined stays invisible
        t1 = await system.search(MemoryQuery(
            metadata_equals={"tenant_id": "t1"}, limit=None))
        assert sorted(e.memory_id for e in t1) == ["a1", "a2"]
        t2 = await system.search(MemoryQuery(
            metadata_equals={"tenant_id": "t2"}, limit=None))
        assert sorted(e.memory_id for e in t2) == ["b1", "b2"]

        # multi-tenant snapshot restore through the REAL contract adapters
        # (export -> restore), not direct engine-internal assignment
        from agos_kernel.agent_production.memory_store import store_for
        snap = system._memories
        fresh = MemorySystem(max_entries=100)
        fresh_store = store_for(fresh)  # the real adapter pick (in-process)
        payload = {"format": "agos-memory/v1", "max_entries": 100,
                   "entries": {mid: {**e.to_dict(), "tags": list(e.tags)}
                               for mid, e in snap.items()}}
        result = await fresh_store.restore(payload)
        assert result["restored"] == 5  # all five landed through the contract
        t1f = await fresh.search(MemoryQuery(
            metadata_equals={"tenant_id": "t1"}, limit=None))
        assert sorted(e.memory_id for e in t1f) == ["a1", "a2"]
        # and the restored engine keeps the same tenant views as the source
        q2 = await fresh.search(MemoryQuery(
            metadata_equals={"tenant_id": "t2"}, limit=None))
        assert sorted(e.memory_id for e in q2) == ["b1", "b2"]

        # forget_tenant (experience layer uses metadata_equals + delete):
        for e in await system.search(MemoryQuery(
                metadata_equals={"tenant_id": "t1"}, limit=None)):
            await system.forget(e.memory_id)
        assert {m for m in system._memories} == {"b1", "b2", "q1"}
        await _assert_index_invariants(system)
        # t2 data untouched and still findable
        t2_after = await system.search(MemoryQuery(
            metadata_equals={"tenant_id": "t2"}, limit=None))
        assert sorted(e.memory_id for e in t2_after) == ["b1", "b2"]

    asyncio.run(scenario())


def test_tenant_isolation_experience_level(monkeypatch, tmp_path):
    """Experience layer: recall and search are tenant-scoped (SEC-02); a
    quarantined (untenanted) record is never recalled; forget_tenant removes
    only that tenant's records; results carry no cross-tenant content."""
    from agent_civilization.core import experience, tenancy

    monkeypatch.setenv("AGOS_MEMORY_FILE", str(tmp_path / "exp.json"))
    experience._memory = None  # force a fresh engine on this path
    experience._loaded = False
    try:
        async def run(tid, text):
            tok = tenancy.set_tenant(tid)
            try:
                return await experience.run_with_experience(
                    "web", "agent-1", {"kind": "text", "prompt": text},
                    lambda: _ok(text))
            finally:
                tenancy.reset_tenant(tok)

        async def _ok(text):
            return {"ok": True, "answer": f"done {text}"}

        async def scenario():
            await run("iso-t1", "goal alpha one")
            await run("iso-t2", "goal beta two")
            # quarantined: stored with no tenant in scope (SEC-02 refuses —
            # run_with_experience returns without storing), so instead put an
            # untenanted record directly in the engine the layer reads:
            st = experience.mem_store()
            await st.write(content="quarantined: goal gamma",
                           memory_type=MemoryType.EPISODIC,
                           tags={"spec:web", "kind:text"},
                           metadata={"layer": "experience", "tenant_id": None,
                                     "specialization": "web", "prompt": "goal gamma",
                                     "words": ["goal", "gamma"]},
                           importance=0.5, memory_id="quarantine-1")

            # tenant 1 recalls only its own goal (recall needs the tenant set)
            tok1 = tenancy.set_tenant("iso-t1")
            try:
                res = await experience.recall("web", {"kind": "text",
                                                       "prompt": "goal alpha one"})
                assert len(res) == 1
                assert "alpha one" in res[0]["prompt"]
                assert not any("beta" in r["prompt"] or "gamma" in r["prompt"]
                               for r in res)
            finally:
                tenancy.reset_tenant(tok1)

            # tenant-scoped search never crosses tenants, quarantined hidden
            t1 = await experience.search(q="goal", scope="iso-t1")
            assert all("alpha" in r["prompt"] for r in t1)
            assert not any("beta" in r["prompt"] or "gamma" in r["prompt"] for r in t1)
            t2 = await experience.search(q="goal", scope="iso-t2")
            assert all("beta" in r["prompt"] for r in t2)
            assert not any("alpha" in r["prompt"] for r in t2)

            # no scope: refused (fail closed), quarantined unreachable
            with pytest.raises(Exception):
                await experience.search(q="goal")
            tok_none = tenancy.set_tenant(None)
            try:
                assert (await experience.recall("web", {"kind": "text",
                                                          "prompt": "goal"})) == []
            finally:
                tenancy.reset_tenant(tok_none)

            # forget_tenant removes ONLY tenant 1's records
            assert await experience.forget_tenant("iso-t1") == 1
            tids = {e.metadata.get("tenant_id") for e in st.entries()}
            assert tids == {"iso-t2", None}  # t2 + quarantined remain

        asyncio.run(scenario())
    finally:
        experience._memory = None
        experience._loaded = False
