"""R-168 durability: real restart, storage failure, concurrency, tenant isolation.

P4 acceptance criteria (R-168):
- a REAL process restart round-trip: write -> persist -> process exits ->
  a NEW process loads and sees content/types/tags/metadata/timestamps/
  access-counters/indexes/search results (no in-process object reuse);
- storage failure (missing file, unreadable file, unwritable dir, ENOSPC
  injection, leftover .tmp) fails closed with no partial state and never
  destroys the last good snapshot;
- asyncio concurrency invariants: records and both indexes never diverge
  under interleaved store/delete/search/persist/load, capacity races stay
  within bounds;
- tenant isolation: recall never crosses tenants; quarantined (untenanted)
  records stay invisible; forget_tenant removes only that tenant's records
  and their index entries.

Thread-based sharing of one MemorySystem is NOT the production model
(single asyncio event loop; the thread pool only wraps blocking IO) —
documented in EVIDENCE, not fixed with a global lock here.
"""
import asyncio
import json
import os
import sys
import tempfile
from pathlib import Path

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from agos_kernel.agent_production.memory_system import (  # noqa: E402
    MemoryQuery,
    MemorySystem,
    MemoryType,
)

WORKER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "r168_worker.py")

SPEC = {
    "max_entries": 100,
    "entries": [
        {"memory_id": "r1", "content": "alpha content one", "memory_type": "episodic",
         "tags": ["alpha", "t1"], "metadata": {"tenant_id": "t1", "k": "v1"},
         "importance": 0.6, "touches": 3},
        {"memory_id": "r2", "content": "beta content two", "memory_type": "semantic",
         "tags": ["beta", "t2"], "metadata": {"tenant_id": "t2"}, "importance": 0.4,
         "touches": 0},
        {"memory_id": "r3", "content": "alpha gamma three", "memory_type": "episodic",
         "tags": ["alpha", "t2"], "metadata": {"tenant_id": "t2"}, "importance": 0.8,
         "touches": 1},
    ],
}


def _run_worker(*args):
    import subprocess
    proc = subprocess.run(
        [sys.executable, WORKER, *args],
        capture_output=True, text=True, timeout=120,
    )
    assert proc.returncode == 0, f"worker failed: {proc.stderr[-500:]}"
    return json.loads(proc.stdout)


# --------------------------------------------------------------- real restart

def test_real_process_restart_roundtrip(tmp_path):
    """Write+persist in ONE process; a NEW process must see everything."""
    spec_path = tmp_path / "spec.json"
    persist_path = tmp_path / "mem.json"
    spec_path.write_text(json.dumps(SPEC), encoding="utf-8")

    _run_worker("seed", str(spec_path), str(persist_path))

    # what the first process actually persisted (the raw snapshot)
    raw = json.loads(persist_path.read_text(encoding="utf-8"))
    assert set(raw) == {"r1", "r2", "r3"}
    assert raw["r1"]["access_count"] == 3  # touches survived the persist

    # a NEW, independent process loads and dumps canonical state
    out = _run_worker("verify", str(persist_path))
    assert out["loaded"] is True
    state = out["state"]
    assert state["total"] == 3
    recs = state["records"]
    # content, type, tags, metadata, importance: exactly as stored
    assert recs["r1"]["content"] == "alpha content one"
    assert recs["r1"]["memory_type"] == "episodic"
    assert recs["r1"]["tags"] == ["alpha", "t1"]
    assert recs["r1"]["metadata"] == {"tenant_id": "t1", "k": "v1"}
    assert recs["r1"]["importance"] == 0.6
    # timestamps preserved exactly (not re-generated by the loader)
    assert recs["r1"]["created_at"] == raw["r1"]["created_at"]
    assert recs["r1"]["last_accessed"] == raw["r1"]["last_accessed"]
    # access counters preserved
    assert recs["r1"]["access_count"] == 3
    assert recs["r2"]["access_count"] == 0
    # indexes rebuilt in the new process
    assert state["index_by_type"]["episodic"] == ["r1", "r3"]
    assert state["index_by_type"]["semantic"] == ["r2"]
    assert state["index_by_tag"]["alpha"] == ["r1", "r3"]
    # search works after restart (results, not the same object)
    assert state["search_episodic"] == ["r1", "r3"]
    assert state["search_tag_alpha"] == ["r1", "r3"]


