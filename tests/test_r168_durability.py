# ------------------------------------------------------------ storage failure

def test_persist_unwritable_dir_fails_closed(tmp_path):
    """A read-only directory: persist fails, the old snapshot stays intact,
    and no .tmp litter is left behind."""
    d = tmp_path / "ro"
    d.mkdir()
    path = str(d / "mem.json")

    async def scenario():
        system = MemorySystem(persistence_file=path)
        await system.store(content="first", memory_type=MemoryType.EPISODIC,
                           memory_id="m1")
        await system._persist_strict()
        raw_before = Path(path).read_text(encoding="utf-8")

        os.chmod(d, 0o555)  # read-only dir (CI and sandbox run non-root)
        try:
            with pytest.raises(OSError):
                await system._persist_strict()
            # the last good snapshot is intact and there is no .tmp litter
            assert Path(path).read_text(encoding="utf-8") == raw_before
            assert not os.path.exists(path + ".tmp")
        finally:
            os.chmod(d, 0o755)

    asyncio.run(scenario())


def test_load_unreadable_file_fails_closed(tmp_path):
    """An unreadable file: load fails closed; existing engine state untouched."""
    path = tmp_path / "mem.json"
    path.write_text("{}", encoding="utf-8")

    async def scenario():
        system = MemorySystem(persistence_file=str(path))
        await system.store(content="keep", memory_type=MemoryType.SEMANTIC,
                           memory_id="k1")
        before = dict(system._memories)
        os.chmod(path, 0o000)
